    private fun sigmoid(x: Double): Double {
        val clipped = max(-500.0, min(500.0, x))
        return 1.0 / (1.0 + exp(-clipped))
    }

    fun forward(urgency: Double, importance: Double, duration: Double, envy: Double, energy: Double): Double {
        // Normalisation entre 0 et 1 car les sliders sont 0-10
        val input = doubleArrayOf(urgency / 10.0, importance / 10.0, duration / 10.0, envy / 10.0, energy / 10.0)

        // Couche cachée (z1 = np.dot(X, w1) + b1)
        val hiddenLayerSize = w1[0].size
        val z1 = DoubleArray(hiddenLayerSize)
        val a1 = DoubleArray(hiddenLayerSize)

        for (j in 0 until hiddenLayerSize) {
            var sum = 0.0
            for (i in input.indices) {
                sum += input[i] * w1[i][j]
            }
            z1[j] = sum + b1[0][j]
            a1[j] = sigmoid(z1[j])
        }

        // Couche de sortie (z2 = np.dot(a1, w2) + b2)
        var z2 = 0.0
        for (j in 0 until hiddenLayerSize) {
            z2 += a1[j] * w2[j][0]
        }
        z2 += b2[0][0]

        // Résultat
        return sigmoid(z2)
    }
